/*
 * Builds the paste ready Apps Script files in apps-script/paste/ from the sources.
 *   intake.gs         = intake/Schema.gs + intake/Code.gs
 *   staff-panel.gs    = staff-panel/Schema.gs + staff-panel/Code.gs
 *   Panel.html        = staff-panel/Panel.html with F003Sheet.html inlined
 * Usage: node tools/build-apps-script.js   (tests/run.js checks the output is up to date)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const A = path.join(__dirname, '..', 'apps-script');
const read = p => fs.readFileSync(path.join(A, p), 'utf8');

function build() {
  const banner = name => '/* ' + name + ': GENERATED by tools/build-apps-script.js. Edit the files in apps-script/intake or apps-script/staff-panel, then rebuild. */\n\n';
  return {
    'intake.gs': banner('intake.gs') + read('intake/Schema.gs') + '\n' + read('intake/Code.gs'),
    'staff-panel.gs': banner('staff-panel.gs') + read('staff-panel/Schema.gs') + '\n' + read('staff-panel/Code.gs'),
    'Panel.html': read('staff-panel/Panel.html').replace("<?!= include_('F003Sheet') ?>", read('staff-panel/F003Sheet.html').trim())
  };
}

module.exports = { build };
if (require.main === module) {
  const out = path.join(A, 'paste');
  fs.mkdirSync(out, { recursive: true });
  const files = build();
  Object.keys(files).forEach(f => fs.writeFileSync(path.join(out, f), files[f]));
  console.log('Wrote ' + Object.keys(files).map(f => 'apps-script/paste/' + f).join(', '));
}
